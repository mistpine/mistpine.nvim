-- Writes lua/mistpine/palette.lua from the mistpine reference spec.
--
--   nvim -l scripts/sync.lua [path/to/mistpine.json]
--
-- Without an argument it reads $MISTPINE_DIR/palette/mistpine.json
-- (default ../mistpine), and falls back to the copy on GitHub.

local URL = "https://raw.githubusercontent.com/mistpine/mistpine/main/palette/mistpine.json"
local root = vim.fs.dirname(vim.fs.dirname(vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p")))
local out = root .. "/lua/mistpine/palette.lua"

local function read(path)
  local f = io.open(path, "r")
  if not f then
    return nil
  end
  local text = f:read("*a")
  f:close()
  return text
end

local source = arg[1]
  or vim.fs.normalize((vim.env.MISTPINE_DIR or (root .. "/../mistpine")) .. "/palette/mistpine.json")
local text = read(source)
if not text then
  source = URL
  local res = vim.system({ "curl", "-fsSL", URL }, { text = true }):wait()
  assert(res.code == 0, "could not download " .. URL .. ": " .. (res.stderr or ""))
  text = res.stdout
end
local spec = vim.json.decode(text)

--- Keys of each top-level object, in the order the spec lists them.
local function key_order(json)
  local order, stack, i = {}, {}, 1
  local expect_key = false
  while i <= #json do
    local ch = json:sub(i, i)
    if ch == '"' then
      local j = i + 1
      while json:sub(j, j) ~= '"' do
        j = j + (json:sub(j, j) == "\\" and 2 or 1)
      end
      local s = json:sub(i + 1, j - 1)
      if expect_key and json:match("^%s*:", j + 1) then
        if #stack == 2 then
          local section = stack[2]
          order[section] = order[section] or {}
          table.insert(order[section], s)
        end
        stack.pending = s
      end
      i = j
    elseif ch == "{" then
      table.insert(stack, stack.pending or "")
      stack.pending = nil
      expect_key = true
    elseif ch == "}" then
      table.remove(stack)
    elseif ch == "," then
      expect_key = true
    elseif ch == ":" then
      expect_key = false
    end
    i = i + 1
  end
  return order
end

local order = key_order(text)

local function q(s)
  return string.format("%q", s)
end

local reserved = {}
for w in
  ("and break do else elseif end false for function goto if in local nil not or repeat return then true until while"):gmatch(
    "%a+"
  )
do
  reserved[w] = true
end

local function key(k)
  if k:match("^[%a_][%w_]*$") and not reserved[k] then
    return k
  end
  return "[" .. q(k) .. "]"
end

--- `mix(@terminal.background, $yellow, 35%)` → { "terminal.background", "yellow", 0.35 }
local function parse_mix(derived)
  local base, color, pct = derived:match("^mix%(@([%w.]+),%s*%$(%w+),%s*([%d.]+)%%%)$")
  assert(base, "unknown blend: " .. derived)
  return string.format("{ %s, %s, %s }", q(base), q(color), tonumber(pct) / 100)
end

--- One resolved color: its hex, where it comes from, and any style.
local function entry(e)
  local parts = { q(e.hex) }
  if e.ref then
    table.insert(parts, "ref = " .. q(e.ref))
  elseif e.derived then
    table.insert(parts, "mix = " .. parse_mix(e.derived))
  end
  for _, style in ipairs({ "bold", "italic", "underline" }) do
    if e[style] then
      table.insert(parts, style .. " = true")
    end
  end
  return "{ " .. table.concat(parts, ", ") .. " }"
end

local lines = {
  "-- mistpine spec: generated by scripts/sync.lua from",
  "-- https://github.com/mistpine/mistpine/blob/main/palette/mistpine.json",
  "-- Do not edit by hand: change the spec upstream, then run `make sync`.",
  "--",
  "-- Each entry is { hex, ref = palette key } or { hex, mix = { base, palette key, amount } },",
  "-- so colors can be re-resolved when a palette key is overridden.",
  "",
  "---@type mistpine.Spec",
  "return {",
  "  name = " .. q(spec.name) .. ",",
  "  variant = " .. q(spec.variant) .. ",",
  "  palette = {",
}
for _, k in ipairs(order.palette) do
  table.insert(lines, string.format("    %s = %s,", key(k), q(spec.palette[k])))
end
table.insert(lines, "  },")
table.insert(lines, "  terminal = {")
for _, k in ipairs(order.terminal) do
  table.insert(lines, string.format("    %s = %s,", key(k), entry(spec.terminal[k])))
end
table.insert(lines, "  },")
table.insert(lines, "  -- ansi[1] is color 0 (black), ansi[16] is color 15 (bright white)")
table.insert(lines, "  ansi = {")
for i, e in ipairs(spec.ansi) do
  table.insert(lines, string.format("    %s, -- %d", entry(e), i - 1))
end
table.insert(lines, "  },")
for _, section in ipairs({ "syntax", "ui" }) do
  table.insert(lines, "  " .. section .. " = {")
  for _, k in ipairs(order[section]) do
    table.insert(lines, string.format("    %s = %s,", key(k), entry(spec[section][k])))
  end
  table.insert(lines, "  },")
end
table.insert(lines, "}")

local f = assert(io.open(out, "w"))
f:write(table.concat(lines, "\n") .. "\n")
f:close()
print("wrote lua/mistpine/palette.lua from " .. source)
